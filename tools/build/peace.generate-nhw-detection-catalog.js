'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { parseArgs } = require('node:util');

const relayRoot = path.resolve(__dirname, '../..');
const nativeRoot = path.resolve(relayRoot, '../Railway/Cozy.NativeHandleWatch/Source');
const catalogPath = path.join(relayRoot, 'contracts/native-monitor/peace.nhw-detections-v1.json');
const silentLabels = {
  dkNamespace: 'Namespace',
  dkDeviceMap: 'Device Map',
  dkAllocation: 'Allocation',
  dkCommit: 'Memory Commit',
  dkMemoryRelease: 'Memory Release',
  dkAllocationBurst: 'Allocation Burst',
  dkReadGap: 'Read Sampling Gap',
};
const warningAlias = ['dkETWLoss', 'dkCoverageGap', 'dkObservationUncertain', 'dkSensorPressure'];
const diagnosticKinds = new Set(['dkTraceGap', 'dkReadGap', 'dkKernelTelemetryGap', ...warningAlias]);

// These are eligible to close a session only after native confirmation. The
// injection and APC producers require independent signals within valid own-target
// observations. Write integrity requires a complete read of the changed canary.
// Kernel trust additionally requires the independent SessionInvalidated latch.
const terminalEvidence = new Set([
  'dkWriteIntegrity', 'dkInjectionEvidence', 'dkAPCStyleEvidence', 'dkSessionTrustUntrusted',
]);

function catalogFromLogging(source) {
  const definition = source.match(/\bTDetectionKind\s*=\s*\(([\s\S]*?)\)\s*;/);
  assert.ok(definition, 'NHW detection enumeration is missing');
  const symbols = definition[1].split(',').map(symbol => symbol.trim());
  assert.equal(symbols.length, 204, 'NHW v109 detection ordinal count changed');
  assert.equal(new Set(symbols).size, symbols.length, 'Duplicate NHW detection symbol');
  assert.ok(symbols.every(symbol => /^dk[A-Za-z0-9]+$/.test(symbol)), 'Invalid NHW detection symbol');

  const labels = new Map();
  const emit = /\bif\s+([\s\S]*?)\s+then\s+Writeln\('([^'\r\n]+)'\)\s*;/g;
  const condition = /^\(?\s*dk[A-Za-z0-9]+\s+in\s+Kinds\s*\)?(?:\s+or\s+\(?\s*dk[A-Za-z0-9]+\s+in\s+Kinds\s*\)?)*$/;
  for (const [, predicate, label] of source.matchAll(emit)) {
    assert.match(predicate, condition, 'Unknown NHW console condition');
    assert.match(label, / Detect$/, 'Unexpected NHW console label');
    for (const symbol of predicate.match(/\bdk[A-Za-z0-9]+/g)) {
      assert.ok(symbols.includes(symbol) && !labels.has(symbol), `Invalid console symbol ${symbol}`);
      labels.set(symbol, label);
    }
  }

  assert.deepEqual(symbols.filter(symbol => !labels.has(symbol)), Object.keys(silentLabels));
  assert.equal(new Set(labels.values()).size, 194, 'NHW v109 console label count changed');
  assert.deepEqual(symbols.filter(symbol => labels.get(symbol) === 'Waring Detect'), warningAlias);
  for (const symbol of [...diagnosticKinds, ...terminalEvidence]) assert.ok(symbols.includes(symbol), symbol);

  return {
    schemaVersion: 1,
    detections: symbols.map((symbol, id) => {
      const legacyLabel = labels.get(symbol) ?? null;
      const terminal = terminalEvidence.has(symbol);
      const kind = terminal ? 'evidence' : diagnosticKinds.has(symbol) ? 'diagnostic' : 'observation';
      return { id, symbol, label: legacyLabel ?? silentLabels[symbol], legacyLabel, kind, terminal };
    }),
  };
}

function writeOrCheck(file, content, check) {
  if (check) {
    assert.equal(fs.readFileSync(file, 'utf8'), content, `Stale NHW catalog output ${file}`);
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

const { values } = parseArgs({
  options: { check: { type: 'boolean' }, logging: { type: 'string' }, 'native-root': { type: 'string' } },
});
const logging = values.logging ? path.resolve(values.logging) : path.join(nativeRoot, 'NHW.Logging.pas');
const catalog = catalogFromLogging(fs.readFileSync(logging, 'utf8'));
writeOrCheck(catalogPath, JSON.stringify(catalog, null, 2) + '\n', values.check);

if (values['native-root']) {
  const symbols = catalog.detections.filter(row => row.terminal).map(row => row.symbol);
  const output = '{ Generated by peace.generate-nhw-detection-catalog.js. }\nconst\n'
    + `  NHWTerminalEvidenceKinds: TDetectionKinds = [${symbols.join(', ')}];\n`;
  writeOrCheck(path.join(path.resolve(values['native-root']), 'NHW.CozyDetectionPolicy.inc'), output, values.check);
}

console.log(`NHW_CATALOG_${values.check ? 'CHECK' : 'GENERATED'}_PASS ${catalog.detections.length} kinds`);
